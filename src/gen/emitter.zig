const std = @import("std");
const ast = @import("../ebnf/ast.zig");
const rt = @import("../runtime/runtime.zig");
const Error = ast.Error;

pub const GenBackend = enum { RecursiveDescent };
pub const GenOptions = struct {
    backend: GenBackend = .RecursiveDescent,
    module_name: []const u8 = "generated",
    start_rule: []const u8, // required
    emit_cli_demo: bool = false,
};

pub const GeneratedFile = struct {
    path: []const u8,
    contents: []const u8,
};

pub const Generated = struct {
    files: []const GeneratedFile,
    pub fn deinit(self: *Generated, alloc: std.mem.Allocator) void {
        // Free path and content slices that were individually allocated.
        for (self.files) |f| {
            alloc.free(f.path);
            alloc.free(f.contents);
        }
        alloc.free(self.files);
        self.* = undefined;
    }
};

pub fn emit(alloc: std.mem.Allocator, grammar: *const ast.AST, opts: GenOptions) !Generated {
    // Validations
    try grammar.ensureNoDuplicates();
    try grammar.ensureDefinedSymbols();
    try grammar.checkReachability(opts.start_rule);
    try grammar.checkEmptyRepetition();
    try grammar.checkLeftRecursion();

    const terminals = try grammar.collectTerminals(alloc);
    defer alloc.free(terminals);

    // Compute skip_ws flag: skip if no terminal contains whitespace
    var skip_ws = true;
    for (terminals) |t| {
        for (t) |c| {
            if (c == ' ' or c == '\t' or c == '\n' or c == '\r') {
                skip_ws = false;
                break;
            }
        }
        if (!skip_ws) break;
    }

    var sb: std.ArrayList(u8) = .{};
    defer sb.deinit(alloc);
    const w = sb.writer(alloc);

    try w.writeAll(
        \\// Code generated by zig-ebnfgen. Do not edit.
        \\const std = @import("std");
        \\
        \\pub const RecognizerError = error{Unexpected, Trailing};
        \\
        \\const Terminal = struct { id: usize, lit: []const u8 };
        \\
        \\const Scanner = struct {
        \\    input: []const u8,
        \\    idx: usize = 0,
        \\    pub fn init(input: []const u8) Scanner { return .{ .input = input }; }
        \\    fn atEnd(self: *const Scanner) bool { return self.idx >= self.input.len; }
        \\    fn save(self: *const Scanner) usize { return self.idx; }
        \\    fn restore(self: *Scanner, m: usize) void { self.idx = m; }
        \\
    );

    if (skip_ws) {
        try w.writeAll(
            \\    fn skipWS(self: *Scanner) void {
            \\        if (true) {
            \\            while (!self.atEnd()) {
            \\                const c = self.input[self.idx];
            \\                if (c == ' ' or c == '\t' or c == '\n' or c == '\r') self.idx += 1 else break;
            \\            }
            \\        }
            \\    }
            \\
        );
    } else {
        try w.writeAll(
            \\    fn skipWS(self: *Scanner) void {
            \\        if (false) {
            \\            while (!self.atEnd()) {
            \\                const c = self.input[self.idx];
            \\                if (c == ' ' or c == '\t' or c == '\n' or c == '\r') self.idx += 1 else break;
            \\            }
            \\        }
            \\    }
            \\
        );
    }

    try w.writeAll(
        \\    fn matchLit(self: *Scanner, lit: []const u8) bool {
        \\        var i: usize = 0;
        \\        if (self.idx + lit.len > self.input.len) return false;
        \\        while (i < lit.len) : (i += 1) if (self.input[self.idx + i] != lit[i]) return false;
        \\        self.idx += lit.len;
        \\        return true;
        \\    }
        \\    fn lexLongest(self: *Scanner) ?Terminal {
        \\        self.skipWS();
        \\        if (self.atEnd()) return null;
        \\        var best: ?Terminal = null;
        \\        // Longest match, break ties by order
        \\        inline for (TERMINALS, 0..) |t, k| {
        \\            const lit = t;
        \\            if (self.idx + lit.len > self.input.len) continue;
        \\            var ok = true;
        \\            var i: usize = 0;
        \\            while (i < lit.len) : (i += 1) {
        \\                if (self.input[self.idx + i] != lit[i]) { ok = false; break; }
        \\            }
        \\            if (!ok) continue;
        \\            if (best == null or lit.len > best.?.lit.len) {
        \\                best = .{ .id = k, .lit = lit };
        \\            }
        \\        }
        \\        return best;
        \\    }
        \\};
        \\
    );

    // Emit terminals array
    try w.writeAll("const TERMINALS = [_][]const u8{");
    for (terminals, 0..) |t, idx| {
        if (idx != 0) try w.writeAll(", ");
        try w.writeAll("\"");
        // Escape quotes/backslashes
        for (t) |c| switch (c) {
            '\\' => try w.writeAll("\\\\"),
            '"' => try w.writeAll("\\\""),
            '\n' => try w.writeAll("\\n"),
            '\r' => try w.writeAll("\\r"),
            '\t' => try w.writeAll("\\t"),
            else => try w.writeByte(c),
        };
        try w.writeAll("\"");
    }
    try w.writeAll("};\n\n");

    // Forward decls for rule functions
    for (grammar.rules) |r| {
        try w.writeAll("fn p_");
        try w.writeAll(r.name);
        try w.writeAll("(s: *Scanner) bool;\n");
    }
    try w.writeAll("\n");

    // Emit rule bodies (recursive-descent with ordered choice)
    for (grammar.rules) |r| {
        try w.writeAll("fn p_");
        try w.writeAll(r.name);
        try w.writeAll("(s: *Scanner) bool {\n");
        try emitExpr(alloc, w, "    ", grammar, r.expr);
        try w.writeAll("}\n\n");
    }

    // recognize API
    try w.writeAll("pub fn recognize_");
    try w.writeAll(opts.start_rule);
    try w.writeAll("(input: []const u8) !void {\n");
    try w.writeAll("    var s = Scanner.init(input);\n");
    try w.writeAll("    if (!p_");
    try w.writeAll(opts.start_rule);
    try w.writeAll("(&s)) return RecognizerError.Unexpected;\n");
    try w.writeAll("    // ensure trailing input is only whitespace\n");
    try w.writeAll("    s.skipWS();\n");
    try w.writeAll("    if (!s.atEnd()) return RecognizerError.Trailing;\n");
    try w.writeAll("}\n\n");

    // Wrap up as a single file module
    const mod_path = try std.fmt.allocPrint(alloc, "{s}/mod.zig", .{opts.module_name});
    const mod_code = try sb.toOwnedSlice(alloc);

    var files: std.ArrayList(GeneratedFile) = .{};
    try files.append(alloc, .{ .path = mod_path, .contents = mod_code });

    // A tiny README for the generated module
    const gen_readme = try std.fmt.allocPrint(alloc, "# {s}\n\nGenerated by zig-ebnfgen. Exposes:\n\n```zig\npub fn recognize_{s}(input: []const u8) !void\n```\n\nErrors:\n* `RecognizerError.Unexpected`\n* `RecognizerError.Trailing`\n", .{ opts.module_name, opts.start_rule });
    const readme_path = try std.fmt.allocPrint(alloc, "{s}/README.generated.md", .{opts.module_name});
    try files.append(alloc, .{ .path = readme_path, .contents = gen_readme });

    return Generated{ .files = try files.toOwnedSlice(alloc) };
}

fn emitExpr(alloc: std.mem.Allocator, w: anytype, indent: []const u8, g: *const ast.AST, e: ast.ExprRef) !void {
    switch (e.*) {
        .literal => |lit| {
            try w.writeAll(indent);
            try w.writeAll("const m = s.save();\n");
            try w.writeAll(indent);
            try w.writeAll("if (!s.matchLit(\"");
            for (lit) |c| switch (c) {
                '\\' => try w.writeAll("\\\\"),
                '"' => try w.writeAll("\\\""),
                '\n' => try w.writeAll("\\n"),
                '\r' => try w.writeAll("\\r"),
                '\t' => try w.writeAll("\\t"),
                else => try w.writeByte(c),
            };
            try w.writeAll("\")) { s.restore(m); return false; }\n");
            try w.writeAll(indent);
            try w.writeAll("return true;\n");
        },
        .empty => {
            try w.writeAll(indent);
            try w.writeAll("return true;\n");
        },
        .ident => |nm| {
            try w.writeAll(indent);
            try w.writeAll("const m = s.save(); if (!p_");
            try w.writeAll(nm);
            try w.writeAll("(s)) { s.restore(m); return false; } return true;\n");
        },
        .opt => |sub| {
            try w.writeAll(indent);
            try w.writeAll("{ // option\n");
            try w.writeAll(indent);
            try w.writeAll("    const m = s.save();\n");
            const new_indent = try std.fmt.allocPrint(alloc, "{s}    ", .{indent});
            defer alloc.free(new_indent);
            try emitExpr(alloc, w, new_indent, g, sub);
            try w.writeAll(indent);
            try w.writeAll("    // if it failed, restore and succeed (option)\n");
            try w.writeAll(indent);
            try w.writeAll("} else s.restore(m);\n");
            try w.writeAll(indent);
            try w.writeAll("return true;\n");
        },
        .rep => |sub| {
            try w.writeAll(indent);
            try w.writeAll("{ // repetition (greedy)\n");
            try w.writeAll(indent);
            try w.writeAll("    while (true) {\n");
            try w.writeAll(indent);
            try w.writeAll("        const mark = s.save();\n");
            const new_indent = try std.fmt.allocPrint(alloc, "{s}        ", .{indent});
            defer alloc.free(new_indent);
            try emitExpr(alloc, w, new_indent, g, sub);
            try w.writeAll(indent);
            try w.writeAll("        else { s.restore(mark); break; }\n");
            try w.writeAll(indent);
            try w.writeAll("    }\n");
            try w.writeAll(indent);
            try w.writeAll("}\n");
            try w.writeAll(indent);
            try w.writeAll("return true;\n");
        },
        .seq => |items| {
            if (items.len == 0) {
                try w.writeAll(indent);
                try w.writeAll("return true;\n");
                return;
            }
            try w.writeAll(indent);
            try w.writeAll("const m = s.save();\n");
            var ok_label_printed = false;
            for (items, 0..) |it, idx| {
                const new_indent = try std.fmt.allocPrint(alloc, "{s}    ", .{indent});
                defer alloc.free(new_indent);
                try emitExpr(alloc, w, new_indent, g, it);
                try w.writeAll(indent);
                try w.writeAll("    ");
                if (idx + 1 != items.len) {
                    try w.writeAll("else { s.restore(m); return false; }\n");
                } else {
                    try w.writeAll("else { s.restore(m); return false; }\n");
                    ok_label_printed = true;
                }
            }
            if (!ok_label_printed) {
                try w.writeAll(indent);
                try w.writeAll("// seq end guard\n");
            }
            try w.writeAll(indent);
            try w.writeAll("return true;\n");
        },
        .choice => |alts| {
            try w.writeAll(indent);
            try w.writeAll("{ // ordered choice\n");
            for (alts) |alt| {
                try w.writeAll(indent);
                try w.writeAll("    { const m = s.save();\n");
                const new_indent = try std.fmt.allocPrint(alloc, "{s}        ", .{indent});
                defer alloc.free(new_indent);
                try emitExpr(alloc, w, new_indent, g, alt);
                try w.writeAll(indent);
                try w.writeAll("    else { s.restore(m); } if (@as(bool, true)) return true; }\n");
            }
            try w.writeAll(indent);
            try w.writeAll("}\n");
            try w.writeAll(indent);
            try w.writeAll("return false;\n");
        },
    }
}
